"use client";

import type { ModelResult } from "@/lib/recommendations";
import { formatCost, formatTime } from "@/lib/recommendations";
import { useState } from "react";

interface Props {
  results: ModelResult[];
  prompt: string;
}

export default function ExportButton({ results, prompt }: Props) {
  const [copied, setCopied] = useState(false);

  const generateMarkdown = (): string => {
    const valid = results.filter((r) => !r.error);
    const lines = [
      "# RouteLab Benchmark Report",
      "",
      `**Task:** ${prompt.slice(0, 200)}${prompt.length > 200 ? "..." : ""}`,
      `**Models compared:** ${valid.length}`,
      `**Generated:** ${new Date().toLocaleString()}`,
      "",
      "---",
      "",
      "## Results",
      "",
    ];

    valid.forEach((r) => {
      lines.push(`### ${r.modelName}`);
      lines.push("");
      lines.push("| Metric | Value |");
      lines.push("|--------|-------|");
      if (r.scores) lines.push(`| Quality Score | ${r.scores.overall}/10 |`);
      lines.push(`| TTFT | ${formatTime(r.ttft)} |`);
      lines.push(`| Total Time | ${formatTime(r.totalTime)} |`);
      lines.push(`| Input Tokens | ${r.inputTokens} |`);
      lines.push(`| Output Tokens | ${r.outputTokens} |`);
      lines.push(`| Cost | ${formatCost(r.totalCost)} |`);
      if (r.scores) {
        lines.push(`| Correctness | ${r.scores.correctness}/10 |`);
        lines.push(`| Clarity | ${r.scores.clarity}/10 |`);
        lines.push(`| Completeness | ${r.scores.completeness}/10 |`);
        lines.push(`| Judge comment | ${r.scores.reason} |`);
      }
      lines.push("");
      lines.push("<details>");
      lines.push("<summary>Full response</summary>");
      lines.push("");
      lines.push("```");
      lines.push(r.response.slice(0, 5000));
      lines.push("```");
      lines.push("");
      lines.push("</details>");
      lines.push("");
    });

    lines.push("---");
    lines.push("");
    lines.push("*Generated by [RouteLab](https://github.com/Aniruddhchilla2407/Alan-AI-OpenFire)*");
    lines.push("");

    return lines.join("\n");
  };

  const copyMarkdown = async () => {
    await navigator.clipboard.writeText(generateMarkdown());
    setCopied(true);
    setTimeout(() => setCopied(false), 2000);
  };

  const copySummary = async () => {
    const valid = results.filter((r) => !r.error);
    const summary = valid
      .map((r) => {
        const parts = [`**${r.modelName}**:`];
        if (r.scores) parts.push(`Score ${r.scores.overall}/10`);
        parts.push(`${formatTime(r.totalTime)}`);
        parts.push(formatCost(r.totalCost));
        return parts.join(" | ");
      })
      .join("\n");
    await navigator.clipboard.writeText(summary);
    setCopied(true);
    setTimeout(() => setCopied(false), 2000);
  };

  if (results.length === 0) return null;

  return (
    <div className="flex gap-2">
      <button
        onClick={copyMarkdown}
        className="flex items-center gap-1.5 px-3 py-1.5 text-xs font-medium rounded-lg bg-zinc-800 border border-zinc-700 text-zinc-300 hover:bg-zinc-700 transition-colors cursor-pointer"
      >
        {copied ? "✓ Copied!" : "📋 Export Markdown"}
      </button>
      <button
        onClick={copySummary}
        className="flex items-center gap-1.5 px-3 py-1.5 text-xs font-medium rounded-lg bg-zinc-800 border border-zinc-700 text-zinc-300 hover:bg-zinc-700 transition-colors cursor-pointer"
      >
        {copied ? "✓ Copied!" : "📋 Copy Summary"}
      </button>
    </div>
  );
}